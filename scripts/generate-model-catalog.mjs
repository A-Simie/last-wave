// Regenerates src/data/newModels.ts from scripts/new-assets.prepared.json (written by prepare-new-assets.mjs).
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entries = JSON.parse(await readFile(path.join(root, 'scripts/new-assets.prepared.json'), 'utf8'));
const LICENSE_URLS = {
    'CC-BY-4.0': 'https://creativecommons.org/licenses/by/4.0/',
    'CC-BY-NC-4.0': 'https://creativecommons.org/licenses/by-nc/4.0/',
    'CC-BY-NC-SA-4.0': 'https://creativecommons.org/licenses/by-nc-sa/4.0/',
    'CC-BY-ND-4.0': 'https://creativecommons.org/licenses/by-nd/4.0/',
    'CC-BY-NC-ND-4.0': 'https://creativecommons.org/licenses/by-nc-nd/4.0/'
};
const round = (v) => Math.round(v * 1000) / 1000;
const lines = entries.map((e) => {
    const author = e.author.replace(/\s*\(https?:[^)]*\)\s*$/, '');
    const authorUrl = /\((https?:[^)]*)\)/.exec(e.author)?.[1] ?? '';
    if (!LICENSE_URLS[e.license]) throw new Error(`Unknown licence ${e.license} for ${e.id}`);
    return `    ${e.id}: {
        file: '${e.file}',
        group: '${e.group}',
        sourceFile: ${JSON.stringify(e.sourceFile)},
        title: ${JSON.stringify(e.title)},
        author: ${JSON.stringify(author)},
        authorUrl: '${authorUrl}',
        source: '${e.url}',
        license: '${e.license}',
        modified: ${!e.verbatim},
        dims: [${e.dims.map(round).join(', ')}],
        scale: ${round(e.runtimeScale)},
        offset: [${e.runtimeOffset.map(round).join(', ')}],
        bytes: ${e.bytes}
    }`;
});
const output = `// Generated by scripts/generate-model-catalog.mjs from scripts/new-assets.prepared.json. Do not edit by hand.
// Every model below is a Sketchfab download supplied in "New FIles"; see docs/ASSET_LICENSES.md.
export const LICENSE_URLS = ${JSON.stringify(LICENSE_URLS, null, 4).replace(/"/g, "'")} as const;

export type ModelLicense = keyof typeof LICENSE_URLS;
export type ModelGroup = 'street' | 'beach' | 'umbrella' | 'vehicle' | 'character' | 'login';
export type PreparedModel = {
    readonly file: string;
    readonly group: ModelGroup;
    readonly sourceFile: string;
    readonly title: string;
    readonly author: string;
    readonly authorUrl: string;
    readonly source: string;
    readonly license: ModelLicense;
    /** False only for ND-licensed files, which ship byte-identical to the download. */
    readonly modified: boolean;
    /** Metre dimensions after the runtime scale; footprint is centred on x/z and seated on y = 0. */
    readonly dims: readonly [number, number, number];
    readonly scale: number;
    readonly offset: readonly [number, number, number];
    readonly bytes: number;
};

export const PREPARED_MODELS = {
${lines.join(',\n')}
} as const satisfies Record<string, PreparedModel>;

export type PreparedModelId = keyof typeof PREPARED_MODELS;
`;
await writeFile(path.join(root, 'src/data/newModels.ts'), output);
console.log(`Wrote ${entries.length} models`);
