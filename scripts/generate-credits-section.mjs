// Rewrites the "Supplied Sketchfab models" section of public/assets/credits.html from src/data/newModels.ts.
// Run after generate-model-catalog.mjs:  node scripts/generate-credits-section.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { PREPARED_MODELS, LICENSE_URLS } = await import(pathToFileURL(path.join(root, 'src/data/newModels.ts')).href);
const NAMES = {
    'CC-BY-4.0': 'CC BY 4.0',
    'CC-BY-NC-4.0': 'CC BY-NC 4.0',
    'CC-BY-NC-SA-4.0': 'CC BY-NC-SA 4.0',
    'CC-BY-ND-4.0': 'CC BY-ND 4.0',
    'CC-BY-NC-ND-4.0': 'CC BY-NC-ND 4.0'
};
const escape = (text) =>
    text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const items = Object.entries(PREPARED_MODELS)
    .map(([, model]) => {
        const author = model.authorUrl
            ? `<a href="${model.authorUrl}">${escape(model.author)}</a>`
            : escape(model.author);
        const change = model.modified
            ? model.license.includes('-SA')
                ? 'Adapted by Last Wave; the adaptation is shared under the same licence.'
                : 'Adapted by Last Wave (optimised geometry/textures, scale and materials).'
            : 'Used unmodified.';
        return `            <li>
                <a href="${model.source}">${escape(model.title)}</a> by ${author} ·
                <a href="${LICENSE_URLS[model.license]}">${NAMES[model.license]}</a> · ${change}
            </li>`;
    })
    .join('\n');
const section = `        <!-- supplied-models:start (generated by scripts/generate-credits-section.mjs) -->
        <h2>Supplied Sketchfab models · Creative Commons</h2>
        <p>
            These downloads are used under the Creative Commons licence named on each line. “NC” models are used only
            in the free, non-commercial build; “ND” models ship byte-identical to the download. Full register and
            swap list: <code>docs/ASSET_LICENSES.md</code>.
        </p>
        <ul>
${items}
        </ul>
        <!-- supplied-models:end -->`;
const file = path.join(root, 'public/assets/credits.html');
let html = await readFile(file, 'utf8');
const start = html.indexOf('        <!-- supplied-models:start');
const endMarker = '<!-- supplied-models:end -->';
if (start >= 0) html = html.slice(0, start) + section + html.slice(html.indexOf(endMarker) + endMarker.length);
else
    html = html.replace(
        '        <h2>Music and original artwork</h2>',
        `${section}\n        <h2>Music and original artwork</h2>`
    );
await writeFile(file, html);
console.log(`Credited ${Object.keys(PREPARED_MODELS).length} supplied models`);
